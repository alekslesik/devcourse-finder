import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {passportCourses} from '../scripts/passport-fixtures.mjs';
import {readFileSync} from 'node:fs';

const template=JSON.parse(readFileSync('../data/demo-catalog.json','utf8')).courses[0];
for(const width of [390,1440])test(`study effort stays separate across catalog, tariffs and comparison: ${width}px`,async({page},info)=>{
 test.skip(process.env.E2E_REAL_API==='1','Presentation-only effort fixture; real publication covered by backend PostgreSQL tests.');
 await page.setViewportSize({width,height:1000});
 await page.emulateMedia({reducedMotion:'reduce'});
 const course=passportCourses(template).find((c:{slug:string})=>c.slug==='passport-effort');
 await page.route('**/api/v1/courses?*',route=>route.fulfill({json:{items:[{course,offer:course.offers[0],effective_price:course.offers[0].price,reasons:[],stale:false}],total:1,page:1,page_size:12}}));
 await page.goto('/courses');
 await expect(page.locator('.card .facts')).toContainText('20–40 ч всего');
 await expect(page.locator('.card .facts')).not.toContainText('ч/нед.');
 await page.locator('.card').getByRole('link',{name:'Подробнее'}).click();
 const fact=(label:string)=>page.locator('.courseFact').filter({has:page.locator('dt').getByText(label,{exact:true})}).locator('dd');
 await expect(fact('Общий объём обучения')).toHaveText('20–40 ч всего');
 await expect(fact('Длительность')).toContainText('Срок прохождения не указан');
 await expect(fact('Нагрузка')).toContainText('Часы в неделю не указаны');
 await page.locator('.courseTariffList').getByRole('radio').nth(1).check();
 await expect(fact('Общий объём обучения')).toHaveText('80–120 ч всего');
 await expect(fact('Длительность')).toHaveText('2–3 мес.');
 await expect(fact('Нагрузка')).toHaveText('5–8 ч/нед.');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath(`effort-detail-${width}.png`),fullPage:true});
 const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();expect(axe.violations.map(v=>v.id)).toEqual([]);
 await page.goto('/compare?offers=effort-self-paced,effort-scheduled,removed');
 const row=(label:string)=>page.getByRole('row').filter({has:page.getByRole('rowheader',{name:label,exact:true})});
 await expect(row('Общий объём обучения')).toContainText('20–40 ч всего');
 await expect(row('Общий объём обучения')).toContainText('80–120 ч всего');
 await expect(row('Общий объём обучения')).toContainText('Недоступно');
 await expect(row('Длительность')).toContainText('Срок прохождения не указан');
 await expect(row('Длительность')).toContainText('2–3 мес.');
 await expect(row('Нагрузка')).toContainText('5–8 ч/нед.');
 await expect(row('Действия').getByRole('link',{name:'Проверить условия'})).toHaveCount(2);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath(`effort-compare-${width}.png`),fullPage:true});
});
